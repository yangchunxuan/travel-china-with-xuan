import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { pathToFileURL } from "node:url";

/*
 * The tour contact panel and the header run on every page, and both validate
 * "?tour=…&package=…&travelers=…" through lib/privateTourInquiryContext.ts.
 * Importing lib/privateTourProducts.ts there put the whole catalogue (three
 * languages, itineraries and FAQs, ~125 KB gzip) into the JavaScript of all
 * pages. This script projects the catalogue onto the few fields that module
 * reads and writes lib/privateTourInquiryIndex.ts, so the client bundle only
 * carries slugs, titles, package ids and priced traveller counts.
 *
 * Run with Node's type stripping, as the inquiry tests do:
 *   node --experimental-strip-types tools/generate-private-tour-inquiry-index.mjs
 *   node --experimental-strip-types tools/generate-private-tour-inquiry-index.mjs --check
 */

const root = process.cwd();
const outputPath = path.join(root, "lib", "privateTourInquiryIndex.ts");
const check = process.argv.includes("--check");

const { privateTourProducts, privateTourPreviewProducts } = await import(
  pathToFileURL(path.join(root, "lib", "privateTourProducts.ts")).href
);
const { getJapaneseTourCopy } = await import(
  pathToFileURL(path.join(root, "lib", "japaneseTourCopy.ts")).href
);
const { japaneseCruiseOverrides } = await import(
  pathToFileURL(path.join(root, "lib", "japaneseCruiseOverrides.ts")).href
);
const { japaneseExpansionOverrides } = await import(
  pathToFileURL(path.join(root, "lib", "japaneseExpansionOverrides.ts")).href
);
const { japaneseSmallGroupOverrides } = await import(
  pathToFileURL(path.join(root, "lib", "japaneseSmallGroupOverrides.ts")).href
);
const { jaPilotCopy } = await import(
  pathToFileURL(path.join(root, "lib", "jaPilotCopy.ts")).href
);
const { jaPilot } = await import(
  pathToFileURL(path.join(root, "lib", "jaPilot.ts")).href
);

function japaneseTitle(slug) {
  const title = slug === jaPilot.tourSlug
    ? jaPilotCopy.tour.title
    : {
        ...getJapaneseTourCopy(slug),
        ...japaneseCruiseOverrides[slug],
        ...japaneseExpansionOverrides[slug],
        ...japaneseSmallGroupOverrides[slug],
      }.title;
  if (!title) throw new Error(`Japanese tour title is missing for ${slug}`);
  return title;
}

// Preview products (visibility "preview") have no Japanese page, so they carry
// no Japanese title and a Japanese inquiry cannot name them.
function projectPrivateTourInquiryIndex(products) {
  return products.map((product) => ({
    slug: product.slug,
    ...(product.visibility === "preview" ? { visibility: "preview" } : {}),
    title: product.visibility === "preview"
      ? { en: product.title.en, zh: product.title.zh, ko: product.title.ko }
      : { en: product.title.en, zh: product.title.zh, ko: product.title.ko, ja: japaneseTitle(product.slug) },
    packages: product.packages.map((tourPackage) => ({
      id: tourPackage.id,
      prices: tourPackage.prices.map((row) => ({ travelers: row.travelers })),
    })),
  }));
}

function render(index) {
  const q = (value) => JSON.stringify(value);
  const entries = index.map((entry) => {
    const packages = entry.packages.map((tourPackage) => {
      const prices = tourPackage.prices
        .map((row) => `{ travelers: ${row.travelers} }`)
        .join(", ");
      return `      { id: ${q(tourPackage.id)}, prices: [${prices}] },`;
    });
    return [
      "  {",
      `    slug: ${q(entry.slug)},`,
      ...(entry.visibility ? [`    visibility: ${q(entry.visibility)},`] : []),
      entry.title.ja === undefined
        ? `    title: { en: ${q(entry.title.en)}, zh: ${q(entry.title.zh)}, ko: ${q(entry.title.ko)} },`
        : `    title: { en: ${q(entry.title.en)}, zh: ${q(entry.title.zh)}, ko: ${q(entry.title.ko)}, ja: ${q(entry.title.ja)} },`,
      "    packages: [",
      ...packages,
      "    ],",
      "  },",
    ].join("\n");
  });

  return `// Generated by tools/generate-private-tour-inquiry-index.mjs from
// lib/privateTourProducts.ts (published, then preview products). Do not edit by hand: run
// \`node --experimental-strip-types tools/generate-private-tour-inquiry-index.mjs\`.
//
// Client code (tour contact panel, header) needs only these fields. Importing
// the full catalogue there would ship every tour's copy and FAQs to all pages.
import type { HomegroundLocale } from "./homegroundI18n";
// @ts-ignore Source-TypeScript tests require the explicit extension.
import type { PrivateTourPriceTier } from "./privateTourProducts.ts";

export interface PrivateTourInquiryIndexEntry {
  readonly slug: string;
  /** Unlisted, noindex preview product: en/zh/ko only, never Japanese. */
  readonly visibility?: "preview";
  readonly title: Readonly<Record<HomegroundLocale, string>> & { readonly ja?: string };
  readonly packages: readonly {
    readonly id: string;
    readonly prices: readonly { readonly travelers: PrivateTourPriceTier["travelers"] }[];
  }[];
}

export const privateTourInquiryIndex: readonly PrivateTourInquiryIndexEntry[] = [
${entries.join("\n")}
];
`;
}

const indexedProducts = [...privateTourProducts, ...privateTourPreviewProducts];
const output = render(projectPrivateTourInquiryIndex(indexedProducts));

// Compared without line endings: a Windows checkout holds the file with CRLF.
const current = await readFile(outputPath, "utf8").catch(() => null);
const upToDate = current?.replace(/\r\n/g, "\n") === output;

if (check) {
  if (!upToDate) {
    console.error(
      "lib/privateTourInquiryIndex.ts is out of date with lib/privateTourProducts.ts.\n" +
        "Run: node --experimental-strip-types tools/generate-private-tour-inquiry-index.mjs",
    );
    process.exit(1);
  }
  console.log(`✓ private tour inquiry index matches ${indexedProducts.length} tours (${privateTourPreviewProducts.length} preview).`);
} else if (upToDate) {
  // Builds run this; leave an unchanged index alone so the checkout stays clean.
  console.log(`private tour inquiry index: ${indexedProducts.length} tours (${privateTourPreviewProducts.length} preview), unchanged`);
} else {
  await writeFile(outputPath, output, "utf8");
  console.log(`private tour inquiry index: ${indexedProducts.length} tours (${privateTourPreviewProducts.length} preview), ${output.length} bytes`);
}
