import { writeFile, readFile } from 'node:fs/promises';
import { germanTourCopies } from '../lib/germanTourCopy.ts';
const names={}, packages={};
for (const [slug,copy] of Object.entries(germanTourCopies)) {
  names[slug]=copy.title;
  for (const pkg of copy.packages) packages[`${slug}:${pkg.id}`]=pkg.label;
}
const output=`// Generated by tools/generate-german-contact-names.mjs. No itineraries in the client bundle.\nexport const germanContactTourNames: Readonly<Record<string,string>> = ${JSON.stringify(names,null,2)};\nexport const germanContactPackageLabels: Readonly<Record<string,string>> = ${JSON.stringify(packages,null,2)};\n`;
const path='lib/germanContactNames.ts';
let old=''; try { old=await readFile(path,'utf8'); } catch {}
if(old!==output) await writeFile(path,output);
console.log(`German contact labels: ${Object.keys(names).length} tours, ${Object.keys(packages).length} options.`);
