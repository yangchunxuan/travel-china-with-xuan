import { writeFile, readFile } from 'node:fs/promises';
import { frenchTourCopies } from '../lib/frenchTourCopy.ts';
const names={}, packages={};
for (const [slug,copy] of Object.entries(frenchTourCopies)) {
  names[slug]=copy.title;
  for (const pkg of copy.packages) packages[`${slug}:${pkg.id}`]=pkg.label;
}
const output=`// Generated by tools/generate-french-contact-names.mjs. No itineraries in the client bundle.\nexport const frenchContactTourNames: Readonly<Record<string,string>> = ${JSON.stringify(names,null,2)};\nexport const frenchContactPackageLabels: Readonly<Record<string,string>> = ${JSON.stringify(packages,null,2)};\n`;
const path='lib/frenchContactNames.ts';
let old=''; try { old=await readFile(path,'utf8'); } catch {}
if(old!==output) await writeFile(path,output);
console.log(`French contact labels: ${Object.keys(names).length} tours, ${Object.keys(packages).length} options.`);
