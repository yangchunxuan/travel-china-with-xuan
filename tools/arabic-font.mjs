// Shared names and rules for the Arabic edition's web font
// (tools/subset-arabic-font.mjs builds it; tools/check-font-coverage.mjs and
// the Arabic edition tests check it).
export const arabicFamily = "Homeground Arabic";
// The complete upstream variable font, converted losslessly to WOFF2. It is the
// subset source and is never published.
export const arabicSourcePath = "tools/fonts/NotoSansArabic-Variable.woff2";
export const arabicFontDirectory = "public/fonts/arabic";
export const arabicCssPath = "app/(arabic)/ar/arabic.css";
// Written by tools/subset-arabic-font.mjs: the URL the Arabic layout preloads.
export const arabicFileModulePath = "lib/homegroundArabicFontFile.ts";
export const arabicFontFile = (hash) => `homeground-arabic.${hash}.woff2`;
// Every Arabic font file this tooling has written, and the retired full font.
export const arabicFontFilePattern = /^(homeground-arabic\.[0-9a-f]{8}|NotoSansArabic-Variable)\.woff2$/;

// Points the one Homeground Arabic @font-face rule at the subset, with the
// weight and width ranges the subset keeps.
export function rewriteArabicFontFace(css, url) {
  let rules = 0;
  const rewritten = css.replace(/@font-face\s*\{[^}]*\}/g, (rule) => {
    if (rule.match(/font-family:\s*['"]([^'"]+)['"]/)?.[1] !== arabicFamily) return rule;
    rules += 1;
    return rule
      .replace(/src:\s*url\(['"][^'"]+['"]\)/, `src: url('${url}')`)
      .replace(/font-weight:\s*[^;]+;/, "font-weight: 400 900;")
      .replace(/font-stretch:\s*[^;]+;/, "font-stretch: 100%;");
  });
  if (rules !== 1) throw new Error(`${arabicCssPath} must declare ${arabicFamily} exactly once (found ${rules})`);
  return rewritten;
}

export function readArabicFontUrl(css) {
  const rule = [...css.matchAll(/@font-face\s*\{([^}]*)\}/g)]
    .map(([, body]) => body)
    .filter((body) => body.match(/font-family:\s*['"]([^'"]+)['"]/)?.[1] === arabicFamily);
  if (rule.length !== 1) throw new Error(`${arabicCssPath} must declare ${arabicFamily} exactly once (found ${rule.length})`);
  const url = rule[0].match(/src:\s*url\(['"]([^'"]+)['"]\)/)?.[1];
  if (!url) throw new Error(`The ${arabicFamily} rule in ${arabicCssPath} has no src url`);
  return url;
}

export function renderArabicFileModule(url) {
  return [
    "// Generated by tools/subset-arabic-font.mjs; do not edit.",
    `export const homegroundArabicFontUrl = ${JSON.stringify(url)};`,
    "",
  ].join("\n");
}
