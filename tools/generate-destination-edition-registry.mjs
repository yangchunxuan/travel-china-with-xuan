// Publishes the city pages of the French, German, Spanish, Arabic and
// Japanese editions from the content that exists. A city page in an edition
// language is one file, content/destinations/<city>/edition.<language>.ts;
// this script finds those files and writes
//   - lib/destinationEditionCities.generated.ts: which cities each language
//     has (small, so headers, footers and links can import it),
//   - lib/destinationEditionLoaders.generated.ts: the lazy loaders the pages use,
//   - app/(<group>)/<language>/destinations/[city]/page.tsx for each language
//     with at least one city (Next's static export refuses a dynamic route
//     with no pages, so a language without content has no route file).
// Adding a language's content files and running this script (npm run
// guide:generate, which also runs before every build) is all it takes to
// publish its city pages. --check fails when a written file is stale.
// Run: node tools/generate-destination-edition-registry.mjs [--check]
import { existsSync, readdirSync, readFileSync, rmSync, mkdirSync, writeFileSync, renameSync } from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";

/** Edition languages, in the order the site lists them, with the route group each one lives in. */
export const destinationEditionRouteGroups = {
  fr: "(french)",
  de: "(german)",
  es: "(spanish)",
  ar: "(arabic)",
  ja: "(japanese)",
};
const languages = Object.keys(destinationEditionRouteGroups);
const editionFile = /^edition\.([a-z]{2})\.ts$/u;

function cityFolders(contentRoot) {
  // A city is a folder that has the English page body (body.en.ts).
  return readdirSync(contentRoot, { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && existsSync(path.join(contentRoot, entry.name, "body.en.ts")))
    .map((entry) => entry.name)
    .sort();
}

/** Every content/destinations/<city>/edition.<language>.ts, by language, in the hub registry's city order. */
export function findDestinationEditionContent(root = process.cwd()) {
  const contentRoot = path.join(root, "content/destinations");
  const registry = readFileSync(path.join(root, "lib/destinationHubs.ts"), "utf8");
  const hubIds = /export const destinationHubIds = \[([\s\S]*?)\] as const;/u.exec(registry)?.[1]
    ?.match(/"([a-z]+)"/gu)?.map((id) => id.slice(1, -1));
  if (!hubIds?.length) throw new Error("Cannot read destinationHubIds from lib/destinationHubs.ts.");
  const folders = cityFolders(contentRoot);
  const cities = Object.fromEntries(languages.map((language) => [language, []]));
  for (const city of folders) {
    for (const file of readdirSync(path.join(contentRoot, city))) {
      if (!file.startsWith("edition.")) continue;
      const language = editionFile.exec(file)?.[1];
      if (!language || !languages.includes(language)) {
        throw new Error(`content/destinations/${city}/${file}: an edition file is named edition.<${languages.join("|")}>.ts.`);
      }
      if (!hubIds.includes(city)) throw new Error(`content/destinations/${city}/${file}: ${city} is not a destination hub.`);
      cities[language].push(city);
    }
  }
  for (const language of languages) cities[language].sort((a, b) => hubIds.indexOf(a) - hubIds.indexOf(b));
  return cities;
}

function citiesModule(cities) {
  const lines = [
    "/* Generated by tools/generate-destination-edition-registry.mjs from content/destinations/<city>/edition.<language>.ts. Do not edit. */",
    "export const generatedDestinationEditionCities = {",
    ...languages.map((language) => `  ${language}: ${JSON.stringify(cities[language])},`),
    "} as const;",
    "",
  ];
  return lines.join("\n");
}

function loadersModule(cities) {
  const lines = [
    "/* Generated by tools/generate-destination-edition-registry.mjs from content/destinations/<city>/edition.<language>.ts. Do not edit. */",
    "export const generatedDestinationEditionLoaders = {",
  ];
  for (const language of languages) {
    lines.push(`  ${language}: {`);
    for (const city of cities[language]) {
      lines.push(`    ${city}: () => import(${JSON.stringify(`../content/destinations/${city}/edition.${language}`)}),`);
    }
    lines.push("  },");
  }
  lines.push("} as const;", "");
  return lines.join("\n");
}

function routeModule(language) {
  return `/* Generated by tools/generate-destination-edition-registry.mjs because content/destinations/<city>/edition.${language}.ts exists. Do not edit. */
import {
  DestinationEditionCityRoute,
  destinationEditionCityMetadata,
  destinationEditionCityParams,
} from "../../../../../components/content/DestinationEditionCityRoute";

export const dynamic = "force-static";
export const dynamicParams = false;

export function generateStaticParams() {
  return destinationEditionCityParams("${language}");
}

export async function generateMetadata({ params }: { params: Promise<{ city: string }> }) {
  return destinationEditionCityMetadata("${language}", (await params).city);
}

export default async function DestinationEditionCityPage({ params }: { params: Promise<{ city: string }> }) {
  return <DestinationEditionCityRoute city={(await params).city} language="${language}" />;
}
`;
}

export function destinationEditionRoutePath(root, language) {
  return path.join(root, "app", destinationEditionRouteGroups[language], language, "destinations", "[city]", "page.tsx");
}

/** The files this script owns: path → content, or null for a route file that must not exist. */
export function destinationEditionOutputs(root = process.cwd()) {
  const cities = findDestinationEditionContent(root);
  return {
    cities,
    files: [
      [path.join(root, "lib/destinationEditionCities.generated.ts"), citiesModule(cities)],
      [path.join(root, "lib/destinationEditionLoaders.generated.ts"), loadersModule(cities)],
      ...languages.map((language) => [destinationEditionRoutePath(root, language), cities[language].length ? routeModule(language) : null]),
    ],
  };
}

function write(filePath, content) {
  mkdirSync(path.dirname(filePath), { recursive: true });
  writeFileSync(`${filePath}.tmp`, content, "utf8");
  renameSync(`${filePath}.tmp`, filePath);
}

function run({ check }) {
  const root = process.cwd();
  const { cities, files } = destinationEditionOutputs(root);
  const stale = [];
  for (const [filePath, content] of files) {
    const current = existsSync(filePath) ? readFileSync(filePath, "utf8").replace(/\r\n?/gu, "\n") : null;
    if (current === content) continue;
    if (check) { stale.push(path.relative(root, filePath)); continue; }
    if (content === null) rmSync(path.dirname(filePath), { recursive: true, force: true });
    else write(filePath, content);
  }
  if (stale.length) throw new Error(`Destination edition files are missing or stale (run npm run guide:generate): ${stale.join(", ")}.`);
  const summary = languages.map((language) => `${language} ${cities[language].length}`).join(", ");
  process.stdout.write(`Destination edition city pages: ${summary}.\n`);
}

const invokedPath = process.argv[1] ? pathToFileURL(path.resolve(process.argv[1])).href : null;
if (invokedPath === import.meta.url) {
  try {
    run({ check: process.argv.includes("--check") });
  } catch (error) {
    process.stderr.write(`${error instanceof Error ? error.message : error}\n`);
    process.exitCode = 1;
  }
}
